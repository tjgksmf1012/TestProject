"""한 업무를 여럿이 맡았을 때 완료 점수를 어떻게 나누는가.

요구사항 정의서 §15 `TASK-006` 은 **"담당자 하나 이상"** 이라고만 적혀
있습니다. 칸반 카드에 이름을 여럿 그리는 화면 일처럼 보이는데,
**화면 일이 아닙니다.**

## ⚠️ 안 나누면 담당자 추가가 곧 점수 부풀리기입니다

`tasks` 를 완료하면 담당자에게 `task_completed` 기여 이벤트가 생기고,
`scoring.py` 가 그걸 10점으로 바꿉니다. 담당자를 여럿 받게 만들면서
**각자에게 온전한 10점**을 주면 이렇게 됩니다.

    업무 1건 · 담당자 1명  →  팀 합계 10점
    업무 1건 · 담당자 5명  →  팀 합계 50점   ← 아무도 더 일하지 않았는데

`docs/05` §2 가 이미 같은 부류를 한 번 겪고 적어 둔 문장입니다.

> **이벤트 개수에 비례하는 보상은 무엇이든 개수 늘리기로 뚫립니다.**

오타 PR 30건이 실제 기능 구현 1건을 이겼던 것과 같은 구멍이고, 이번 것이
더 쌉니다 — 커밋을 쪼갤 필요도 없이 **드롭다운에서 이름을 고르면** 됩니다.

## 그래서: 양(量)은 나누고, 여부(與否)는 안 나눕니다

| 무엇 | 나누는가 | 왜 |
|---|---|---|
| 완료 점수 (`task_completed`) | **나눕니다** | 업무 하나가 만드는 총량은 언제나 1 |
| 마감 준수 (`deadline_met/missed`) | **안 나눕니다** | 지켰나 못 지켰나는 각자의 사실 |

마감 준수는 `_schedule_raw` 가 `met / (met + missed)` **비율**로 씁니다.
합산이 아니라서 사람이 늘어도 부풀지 않고, 반대로 절반씩 나누면
"둘이 맡은 마감은 반만 지킨 것" 이라는 이상한 뜻이 됩니다.

## ⚠️ 분모는 **담당자 수가 아니라 완료 이벤트 수**입니다

처음에는 "지금 담당자가 N 명이면 1/N" 으로 짰습니다. 그게 틀렸습니다.

    A·B 가 맡음 → 완료 → 각자 이벤트 1건 (0.5 씩, 합 1.0)
    B 를 담당자에서 뺌 → 지금 담당자는 1 명 → 몫이 1/1 = 1.0
    그런데 B 의 이벤트는 **남아 있습니다** (기여 이벤트는 append-only)
    → A 1.0 + B 1.0 = 2.0                      ← 뺐더니 총량이 늘었다

담당자 셋을 얹고 완료한 뒤 둘을 빼면 총량이 3.0 이 됩니다. **빼는 것이
점수를 올리는 통로**가 됩니다.

완료 이벤트 수로 나누면 그 구멍이 **구조적으로** 막힙니다. 분모가 곧
분자들의 개수라, 담당자를 어떻게 바꾸든 한 업무의 총량은 정확히 1 입니다.
그리고 이 값은 **바뀌지 않는 기록**(이벤트 로그)에서만 나옵니다 —
`docs/05` §1 의 `점수 = f(불변 이벤트 로그, 가중치 버전, 역할)` 그대로입니다.

## ⚠️ 저장하지 않습니다

`share` 를 이벤트 메타데이터에 적어 얼려 두면, 담당자가 나중에 늘었을 때
먼저 있던 사람의 몫이 안 줄어듭니다. `scoring_service.load_events` 가
**읽을 때마다 다시 셉니다** — 같은 파일의 `fulfilled`(지켜진 약속)과
똑같은 처리이고, 이 저장소가 여덟 번째로 같은 판단을 하는 자리입니다.
"""

from __future__ import annotations

#: 업무 하나가 만드는 완료 점수의 총량. 담당자가 몇이든 이 값입니다.
TASK_TOTAL = 1.0


def split_share(completions: int) -> float:
    """완료 이벤트가 `completions` 건일 때 한 건의 몫.

    ⚠️ **인자는 담당자 수가 아니라 완료 이벤트 수입니다.** 왜 그런지는 이
    모듈 머리말에 있습니다. 이름을 `assignees` 로 바꾸고 싶어지면 거기부터
    읽으십시오.

    0 이하는 나눌 것이 없다는 뜻이라 온전한 몫을 돌려줍니다 — 이벤트가
    0건이면 애초에 이 함수를 부를 일이 없고, 음수는 있을 수 없습니다.
    방어적으로 1.0 을 주는 이유는 **깎는 쪽으로 틀리지 않기 위해서**입니다.
    """
    if completions <= 1:
        return TASK_TOTAL
    return TASK_TOTAL / completions

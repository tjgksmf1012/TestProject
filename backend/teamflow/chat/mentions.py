"""본문에서 `@이름` 을 뽑는다 (CHAT-005).

## ⚠️ 왜 서버가 뽑는가

화면이 "누구를 멘션했다" 는 목록을 보내면, 그걸 그대로 믿는 서버는
**아무나 아무에게나 알림을 쏠 수 있게** 됩니다. 본문에는 `@아무개` 가
없는데 목록에만 스무 명을 적어 보내면 그만입니다.

그래서 판정은 **본문에서만** 나옵니다. 화면이 보내는 것은 글자뿐입니다.

## ⚠️ 한국어라서 어려운 점

`@윤식씨` 라고 쓰면 이름은 `윤식` 이고 `씨` 는 호칭입니다. `@윤식은` 이면
`은` 은 조사입니다. 그런데 이름이 `윤식은` 인 사람도 있을 수 있습니다.

**가장 긴 것부터 맞춰 봅니다.** 후보 이름 목록(그 프로젝트의 팀원)을
받아서, `@` 뒤 글자열의 **앞부분과 정확히 일치하는 가장 긴 이름**을
고릅니다. 이름 목록이 없으면 아무도 안 부른 것입니다 — 지어내지 않습니다.

이 방식이면 `@윤식은` 은 팀에 `윤식은` 이 있으면 그 사람, 없고 `윤식` 만
있으면 `윤식` 이 됩니다. 둘 다 있으면 긴 쪽이 이깁니다.

## ⚠️ 화면의 강조는 판정이 아닙니다

화면도 `@무언가` 를 눈에 띄게 그립니다. 그건 **꾸미기**이고, 누가 알림을
받는지와 아무 상관이 없습니다. 두 벌처럼 보이지만 하는 일이 다릅니다 —
화면이 잘못 강조해도 알림은 안 갑니다.
"""

from __future__ import annotations

import re

#: `@` 뒤에 올 수 있는 글자. 공백·문장부호 앞에서 끊습니다.
#:
#: ⚠️ `\w` 를 쓰면 안 됩니다. 파이썬 `re` 에서 `\w` 는 한글을 포함하지만,
#: 이 저장소는 **`\w` 가 한글을 안 잡는다고 믿고 틀린 적**이 있습니다
#: (가드에 위반을 심다가). 여기서는 무엇이 포함되는지 눈에 보이게 적습니다.
_AFTER_AT = re.compile(r"@([0-9A-Za-z가-힣_.\-]+)")


def find_mentions(body: str, candidates: list[str]) -> list[str]:
    """본문이 부른 사람들의 이름. **후보에 있는 것만.**

    ⚠️ 후보에 없는 `@아무개` 는 **버립니다.** 이름을 지어내면 알림이 갈
    곳이 없는데도 "불렀다" 는 기록만 남습니다.

    ⚠️ 순서는 **본문에 나온 순서**이고 중복은 없앱니다. 정렬하지 않습니다 —
    부르는 쪽이 "먼저 부른 사람" 을 알 수 있어야 합니다.
    """
    if not candidates:
        return []

    # 긴 이름이 먼저 맞아야 `@윤식은` 이 `윤식은` 으로 잡힙니다.
    by_length = sorted(candidates, key=len, reverse=True)

    found: list[str] = []
    for match in _AFTER_AT.finditer(body):
        tail = match.group(1)
        for name in by_length:
            if tail.startswith(name) and name not in found:
                found.append(name)
                break
    return found


def strip_mention_marks(body: str) -> str:
    """`@` 를 뗀 본문. **검색에만** 씁니다 (CHAT-010).

    ⚠️ 화면에 이걸 그리지 마십시오. 사람이 쓴 글자를 바꿔서 보여 주면
    "내가 그렇게 안 썼는데" 가 됩니다.
    """
    return _AFTER_AT.sub(r"\1", body)

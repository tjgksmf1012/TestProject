import { withJosa } from '../text/josa.ts';

/**
 * **못 불러왔을 때 뭐라고 할 것인가.**
 *
 * ## 왜 한 벌로 올렸나
 *
 * 화면마다 각자 문구를 짓고 있었고, 둘 다 틀려 있었습니다.
 *
 *  · 설정 화면은 서버가 **404** 를 준 프로젝트를 **「팀원 0명」** 이라고
 *    단언했습니다. 못 받은 것과 정말 0명인 것이 같은 말이 된 것이고,
 *    이 제품의 불변식 셋째(**측정 불가 ≠ 0점**)를 어긴 자리입니다.
 *    게다가 "없는 프로젝트" 와 "빈 팀" 을 사람이 구별할 수 없습니다.
 *
 *  · 기여도 화면은 무슨 일이 있었든 **「네트워크를 확인한 뒤
 *    새로고침하세요」** 라고 했습니다. 없는 프로젝트를 열어도 그렇게
 *    말합니다 — 네트워크는 멀쩡한데 사람은 와이파이를 껐다 켭니다.
 *
 * 서로 다른 사실을 같은 말로 덮으면, 사람은 **고칠 수 없는 것을 고치려
 * 애씁니다.** 무엇이 일어났는지에 따라 할 일이 다릅니다.
 *
 * ⚠️ 상태 코드를 그대로 보여 주지 않습니다 — `요청이 실패했습니다
 *    (HTTP 422)` 는 사람에게 아무 말도 아닙니다. 다만 아주 모르는
 *    경우에는 숨기지 않고 덧붙입니다(제보할 때 쓸 수 있는 유일한 단서).
 */
export function describeLoadFailure(what: string, status: number | null): string {
  // ⚠️ `null` 은 **네트워크가 끊긴 것**입니다. 서버가 준 답이 아닙니다.
  if (status === null || status === 0) {
    return '서버에 연결하지 못했습니다. 네트워크를 확인한 뒤 다시 시도하세요.';
  }
  if (status === 401) return '로그인이 풀렸습니다. 다시 로그인해 주세요.';
  // ⚠️ 403 과 404 를 **같은 말로 덮지 않습니다.** "볼 권한이 없다" 와
  //    "그런 것이 없다" 는 사람이 할 일이 다릅니다 — 앞은 팀에 요청해야
  //    하고 뒤는 주소를 고쳐야 합니다.
  if (status === 403) return `이 ${withJosa(what, '을를')} 볼 권한이 없습니다.`;
  if (status === 404) {
    return `이 ${withJosa(what, '을를')} 찾을 수 없습니다. 주소가 맞는지 확인해 주세요.`;
  }
  if (status >= 500) return '서버에 문제가 있습니다. 잠시 뒤 다시 시도하세요.';
  return `${withJosa(what, '을를')} 불러오지 못했습니다 (HTTP ${status}).`;
}

/**
 * **보냈는데 안 됐을 때 뭐라고 할 것인가.**
 *
 * ⚠️ 검토 화면의 「검토 끝내기」는 서버가 **500 을 줘도 화면이 아무 말도
 * 안 했습니다** (결함 218). 재서 확인한 것 — 누른 뒤 화면 글자가 **한
 * 글자도 안 바뀌었고**, 버튼은 다시 눌리는 상태로 돌아갔습니다. 사람은
 * 확정된 줄 알고 그 화면을 떠납니다. 이 제품에서 그 회의의 업무 후보는
 * 그대로 미결로 남고, 아무도 그 사실을 모릅니다.
 *
 * 원인은 `mutate(payload, { onSuccess })` 에 **`onError` 가 없던 것**입니다.
 * 감싼 `try/catch` 는 payload 를 만드는 동안의 오류만 잡습니다 — 비동기
 * 실패는 그 밖에서 일어납니다.
 *
 * ## 왜 `describeLoadFailure` 와 따로인가
 *
 * 같은 상태 코드라도 **할 일이 다릅니다.** 못 불러온 화면에서 404 는
 * "주소를 고쳐라" 이지만, 보낸 뒤의 404 는 "내가 정하는 사이에 그것이
 * 없어졌다" 입니다. 409 도 여기서만 뜻이 있습니다 — 남이 먼저 했다는
 * 뜻이라 **다시 눌러도 안 되고**, 새로 받아 봐야 합니다.
 *
 * ⚠️ **"다시 시도하세요" 를 아무 데나 붙이지 않습니다.** 다시 눌러도 안
 * 되는 실패(권한·충돌·잘못된 요청)에 그렇게 쓰면, 사람은 되지 않는 것을
 * 반복하다 제품을 불신하게 됩니다.
 */
export function describeActionFailure(what: string, status: number | null): string {
  const 를 = withJosa(what, '을를');
  if (status === null || status === 0) {
    // ⚠️ **"안 됐다" 고 단언하지 않습니다.** 요청이 서버에 닿은 뒤 답만
    //    못 받았을 수도 있습니다. 확인하라고 말하는 것이 정직합니다.
    return `${를} 보냈지만 답을 받지 못했습니다. 네트워크를 확인하고, 새로고침해서 처리됐는지 보세요.`;
  }
  if (status === 401) return '로그인이 풀렸습니다. 다시 로그인한 뒤 시도해 주세요.';
  if (status === 403) return `이 ${를} 할 권한이 없습니다.`;
  if (status === 404) return `대상이 없습니다 — 정하는 사이에 지워졌을 수 있습니다. 새로고침해 보세요.`;
  if (status === 409) {
    return `다른 사람이 먼저 처리했습니다. 새로고침해서 지금 상태를 보고 다시 정해 주세요.`;
  }
  if (status >= 500) return `${를} 처리하지 못했습니다. 잠시 뒤 다시 시도하세요.`;
  return `${를} 처리하지 못했습니다 (HTTP ${status}).`;
}

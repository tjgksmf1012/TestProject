import { withJosa } from '../text/josa.ts';

/**
 * **못 불러왔을 때 뭐라고 할 것인가.**
 *
 * ## 왜 한 벌로 올렸나
 *
 * 화면마다 각자 문구를 짓고 있었고, 둘 다 틀려 있었습니다.
 *
 *  · 설정 화면은 서버가 **404** 를 준 프로젝트를 **「팀원 0명」** 이라고
 *    단언했습니다. 못 받은 것과 정말 0명인 것이 같은 말이 된 것이고,
 *    이 제품의 불변식 셋째(**측정 불가 ≠ 0점**)를 어긴 자리입니다.
 *    게다가 "없는 프로젝트" 와 "빈 팀" 을 사람이 구별할 수 없습니다.
 *
 *  · 기여도 화면은 무슨 일이 있었든 **「네트워크를 확인한 뒤
 *    새로고침하세요」** 라고 했습니다. 없는 프로젝트를 열어도 그렇게
 *    말합니다 — 네트워크는 멀쩡한데 사람은 와이파이를 껐다 켭니다.
 *
 * 서로 다른 사실을 같은 말로 덮으면, 사람은 **고칠 수 없는 것을 고치려
 * 애씁니다.** 무엇이 일어났는지에 따라 할 일이 다릅니다.
 *
 * ⚠️ 상태 코드를 그대로 보여 주지 않습니다 — `요청이 실패했습니다
 *    (HTTP 422)` 는 사람에게 아무 말도 아닙니다. 다만 아주 모르는
 *    경우에는 숨기지 않고 덧붙입니다(제보할 때 쓸 수 있는 유일한 단서).
 */
export function describeLoadFailure(what: string, status: number | null): string {
  // ⚠️ `null` 은 **네트워크가 끊긴 것**입니다. 서버가 준 답이 아닙니다.
  if (status === null || status === 0) {
    return '서버에 연결하지 못했습니다. 네트워크를 확인한 뒤 다시 시도하세요.';
  }
  if (status === 401) return '로그인이 풀렸습니다. 다시 로그인해 주세요.';
  // ⚠️ 403 과 404 를 **같은 말로 덮지 않습니다.** "볼 권한이 없다" 와
  //    "그런 것이 없다" 는 사람이 할 일이 다릅니다 — 앞은 팀에 요청해야
  //    하고 뒤는 주소를 고쳐야 합니다.
  if (status === 403) return `이 ${withJosa(what, '을를')} 볼 권한이 없습니다.`;
  if (status === 404) {
    return `이 ${withJosa(what, '을를')} 찾을 수 없습니다. 주소가 맞는지 확인해 주세요.`;
  }
  if (status >= 500) return '서버에 문제가 있습니다. 잠시 뒤 다시 시도하세요.';
  return `${withJosa(what, '을를')} 불러오지 못했습니다 (HTTP ${status}).`;
}

/**
 * **보냈는데 안 됐을 때 뭐라고 할 것인가.**
 *
 * ⚠️ 검토 화면의 「검토 끝내기」는 서버가 **500 을 줘도 화면이 아무 말도
 * 안 했습니다** (결함 218). 재서 확인한 것 — 누른 뒤 화면 글자가 **한
 * 글자도 안 바뀌었고**, 버튼은 다시 눌리는 상태로 돌아갔습니다. 사람은
 * 확정된 줄 알고 그 화면을 떠납니다. 이 제품에서 그 회의의 업무 후보는
 * 그대로 미결로 남고, 아무도 그 사실을 모릅니다.
 *
 * 원인은 `mutate(payload, { onSuccess })` 에 **`onError` 가 없던 것**입니다.
 * 감싼 `try/catch` 는 payload 를 만드는 동안의 오류만 잡습니다 — 비동기
 * 실패는 그 밖에서 일어납니다.
 *
 * ## 왜 `describeLoadFailure` 와 따로인가
 *
 * 같은 상태 코드라도 **할 일이 다릅니다.** 못 불러온 화면에서 404 는
 * "주소를 고쳐라" 이지만, 보낸 뒤의 404 는 "내가 정하는 사이에 그것이
 * 없어졌다" 입니다. 409 도 여기서만 뜻이 있습니다 — 남이 먼저 했다는
 * 뜻이라 **다시 눌러도 안 되고**, 새로 받아 봐야 합니다.
 *
 * ⚠️ **"다시 시도하세요" 를 아무 데나 붙이지 않습니다.** 다시 눌러도 안
 * 되는 실패(권한·충돌·잘못된 요청)에 그렇게 쓰면, 사람은 되지 않는 것을
 * 반복하다 제품을 불신하게 됩니다.
 */
export function describeActionFailure(
  what: string,
  status: number | null,
  /**
   * 서버가 **사람에게 쓴 문장** (`ApiError.detail`). 409 에서는 이것이
   * 일반론보다 언제나 낫습니다 — 아래 참고.
   */
  detail?: string | null,
): string {
  const 를 = withJosa(what, '을를');
  if (status === null || status === 0) {
    // ⚠️ **"안 됐다" 고 단언하지 않습니다.** 요청이 서버에 닿은 뒤 답만
    //    못 받았을 수도 있습니다. 확인하라고 말하는 것이 정직합니다.
    return `${를} 보냈지만 답을 받지 못했습니다. 네트워크를 확인하고, 새로고침해서 처리됐는지 보세요.`;
  }
  if (status === 401) return '로그인이 풀렸습니다. 다시 로그인한 뒤 시도해 주세요.';
  if (status === 403) return `이 ${를} 할 권한이 없습니다.`;
  if (status === 404) return `대상이 없습니다 — 정하는 사이에 지워졌을 수 있습니다. 새로고침해 보세요.`;
  if (status === 409) {
    /* ⛔ 예전에는 「**다른 사람이 먼저 처리했습니다.** 새로고침해서 지금
       상태를 보고 다시 정해 주세요」였습니다 (결함 300).

       이 제품의 409 를 **전부 세어 봤더니 다섯인데 하나도 그 뜻이
       아닙니다** — 저장소가 이미 남의 프로젝트 것 · 저장소가 아직 연결 안
       됨 · 서버에 GitHub App 자격 증명 없음 · 실패·대기 중인 회의만 다시
       처리 가능 · 확정할 기여도가 없음. 전부 **조건이 안 맞는다**이고,
       새로고침해도 영원히 그대로입니다.

       재현: 「지난 활동 가져오기」를 누르면 서버는 「서버에 GitHub App
       자격 증명이 없거나 App이 아직 이 저장소에 설치되지 않았습니다」
       라고 정확히 말하는데, 화면은 「다른 사람이 먼저 처리했습니다」
       라고 **없던 사람을 지어내** 말하고 있었습니다.

       바로 위 머리말이 금지한 그것입니다 — 「다시 시도하세요」를 다시
       눌러도 안 되는 실패에 붙이면 사람은 되지 않는 것을 반복합니다. */
    const said = (detail ?? '').trim();
    if (said !== '') return said;
    // 서버가 아무 말도 안 했으면 **원인을 지어내지 않습니다.**
    return `지금 상태에서는 ${를} 할 수 없습니다.`;
  }
  if (status >= 500) return `${를} 처리하지 못했습니다. 잠시 뒤 다시 시도하세요.`;
  return `${를} 처리하지 못했습니다 (HTTP ${status}).`;
}

/**
 * 이 실패는 **세션이 끝났다**는 뜻인가.
 *
 * ## ⛔ 말만 하고 갈 자리를 안 줬습니다 (결함 227)
 *
 * 세션이 죽은 뒤의 화면은 이렇습니다.
 *
 *     기여도
 *     로그인이 풀렸습니다. 다시 로그인해 주세요.
 *
 * 그 화면에서 누를 수 있는 것은 **홈 · 칸반 · 기여도 · 설정 · 로그아웃**
 * 뿐이고, 로그인으로 가는 링크는 **한 개도 없습니다.** 길잡이를 눌러도
 * 라우터가 같은 껍데기 안에서 옮길 뿐이라 여전히 로그인 화면이 아닙니다.
 *
 * `RequireAuth` 는 `useMe` 를 보는데 그쪽은 `staleTime: 60_000` 입니다.
 * 재 봤습니다 — 화면 넷을 돌아가며 눌러도 **36초까지는 그대로**였고,
 * 60초쯤에야 `me` 가 낡아 다시 물으면서 풀렸습니다. 그 1분 동안 사람은
 * **멀쩡해 보이는데 아무것도 안 되는 앱**을 누르고 다닙니다.
 *
 * 그래서 판단을 여기 둡니다: **읽든 쓰든 401 이면 그 세션은 끝난 것**이고,
 * 앱은 그 사실을 `me` 에 반영해야 합니다. 그러면 `RequireAuth` 가 사람을
 * 로그인 화면으로 보냅니다 — 그게 「다시 로그인해 주세요」 라고 말해 놓고
 * 줘야 하는 **자리**입니다.
 *
 * ⚠️ 403 은 아닙니다. 그건 "로그인은 됐는데 이 일은 못 한다" 라서,
 * 내보내면 멀쩡한 세션을 끊는 것입니다.
 */
export function sessionIsOver(status: number | null): boolean {
  return status === 401;
}

/**
 * 문 앞에서 내리는 판단 — **들여보낼까, 로그인으로 보낼까, 못 물어봤다고 할까.**
 *
 * ## ⛔ 못 물어본 것을 「로그아웃」이라고 단언했습니다 (결함 282)
 *
 * `RequireAuth` 가 이랬습니다.
 *
 *     if (me === null || me === undefined) return <Navigate to="/login" />;
 *
 * 그런데 그 둘은 **다른 사실**이고, 이 앱은 이미 그 둘을 가르고 있습니다.
 *
 *     null       서버가 401 로 답했다 — **정말 로그인 전**
 *     undefined  물어봤는데 **답을 못 받았다** (끊김·500)
 *
 * 지하철에서 재 봤습니다(연결을 끊고 `/app/` 을 다시 열기) — 세션 쿠키는
 * 멀쩡한데 화면이 **로그인 화면**으로 갑니다. 거기서 아이디와 비밀번호를
 * 치면 그것도 실패합니다(같은 네트워크). 사람은 「로그아웃됐나 보다」
 * 또는 「앱이 고장났다」로 읽고, 정작 할 일(연결을 되살리는 것)은 아무도
 * 안 알려 줍니다.
 *
 * 이 저장소의 불변식 셋째(**측정 불가 ≠ 0점**)가 인증에도 그대로
 * 적용됩니다 — **못 잰 것은 「없음」이 아닙니다.**
 *
 * ⚠️ `'checking'` 과 `'unreachable'` 을 가르는 것은 **실패했는가**입니다.
 * 아직 도는 중인 것을 「못 닿았다」고 하면, 느린 회선에서 멀쩡한 앱이
 * 오류 화면부터 보여 줍니다.
 */
export type AuthGate =
  /** 아직 묻는 중 */
  | 'checking'
  /** 들여보낸다 */
  | 'in'
  /** 서버가 401 로 답했다 — 로그인 화면으로 */
  | 'out'
  /** 물어봤는데 답을 못 받았다 — **로그아웃이 아니다** */
  | 'unreachable';

export function authGate(pending: boolean, me: unknown, failed: boolean): AuthGate {
  if (pending) return 'checking';
  // 서버가 「로그인 전」이라고 **답한** 것. `useMe` 가 401 을 여기로 접습니다.
  if (me === null) return 'out';
  if (me !== undefined) return 'in';
  // 답이 없다. 실패로 끝났으면 못 닿은 것이고, 아니면 아직 도는 중입니다.
  return failed ? 'unreachable' : 'checking';
}

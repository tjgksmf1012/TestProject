/**
 * **회의를 뭐라고 부를 것인가** — 한 벌.
 *
 * ## 같은 회의가 화면마다 다른 이름이었습니다 (결함 285)
 *
 * 「회의 열기」는 제목을 안 묻습니다(결함 268). 그래서 이름 없는 회의는
 * 드문 사고가 아니라 **평범한 상태**입니다. 그런데 이름을 지어 주는 자리가
 * 화면마다 따로 있었고, 여섯이 다 달랐습니다 — 씨앗 회의 4번 하나를 두고:
 *
 * | 어디 | 뭐라고 불렀나 |
 * |---|---|
 * | 홈 목록 | 제목 없는 회의 |
 * | 홈 리본 라벨(낭독기) | 회의 |
 * | 로비 머리줄·브라우저 탭 | **회의 준비** |
 * | 검토 머리줄·브라우저 탭 | **회의 검토** |
 * | 칸반 카드의 출처 | 회의 |
 * | 회의록(서버) | 회의 #4 |
 *
 * 굵게 칠한 둘은 **회의의 이름이 아니라 화면의 이름**입니다. 사람이
 * 「회의 준비」라는 회의를 열었다고 읽습니다. 게다가 탭 이름이 그것이라
 * 이름 없는 회의를 둘 열면 **탭 둘이 글자 하나 안 틀리고 똑같습니다** —
 * 어느 탭이 어느 회의인지 알 방법이 없습니다.
 *
 * 그래서 이름은 **무엇을 부르는지**와 **어느 것인지** 둘 다 말해야 합니다.
 * 번호는 주소창의 그 번호입니다(`/meeting/4/review`) — 사람이 서로에게
 * 가리킬 수 있는 유일한 값입니다.
 *
 * ⚠️ 서버(`report_service`)에도 같은 판단이 **한 벌 더** 있습니다. 언어가
 * 달라 어쩔 수 없이 두 벌인데, 갈라지면 회의록만 다른 이름을 씁니다 —
 * `backend/tests/test_report_service.py` 가 이 모양을 그대로 못 박습니다.
 */
export function meetingLabel(
  title: string | null | undefined,
  id: number | null | undefined,
): string {
  const named = (title ?? '').trim();
  if (named !== '') return named;
  /* 번호를 모르는 자리는 없어야 하지만(회의를 그리려면 id 가 필요합니다),
     타입이 허락하는 한 거짓말은 안 합니다 — 모르면 번호를 안 붙입니다. */
  return typeof id === 'number' ? `제목 없는 회의 #${id}` : '제목 없는 회의';
}

/**
 * 활동 기록이 비었을 때 할 말.
 *
 * ## ⛔ 「아직 아무도 안 바꿨습니다」는 거짓이었습니다 (결함 304)
 *
 * 화면이 이렇게 말하고 있었습니다.
 *
 *     아직 기록된 활동이 없습니다
 *     기록은 누가 무언가를 바꿀 때 쌓입니다 — **아직 아무도 안 바꿨습니다.**
 *
 * 그런데 같은 순간 그 팀에는 **회의 다섯 · 업무 카드 넷 · 세 사람의 기여도
 * 근거**가 있었습니다. 사람들은 한참을 일했습니다.
 *
 * 무엇이 어긋났나 — `what`(「기록된 활동이 없습니다」)은 참입니다. 거짓은
 * **`why`** 쪽입니다. 화면은 자기 목록이 빈 것만 확인해 놓고 **팀 전체가
 * 아무것도 안 했다**고 단언했습니다. 결함 294(일정 화면)와 같은 모양이고,
 * 이 저장소가 그때 적어 둔 규칙이 이것입니다 —
 *
 * > 빈 상자를 지을 때는 「무엇이 비었나」와 「무엇이 있나」를 갈라 보십시오.
 *
 * ## 왜 바쁜 팀인데도 비어 있나
 *
 * `audit_logs` 는 **사람이 손으로 내린 결정**만 받습니다. 서버가 쓰는 갈래를
 * 세어 보면 **열넷**이고 전부 그 성질입니다 — 업무 후보 승인·거절, 업무
 * 완료·되돌림·삭제·담당자 변경, 역할 비중, 기여도 조정, AI 출력 교정, 회의
 * 재처리, 오디오·성문·내 데이터 폐기, GitHub 계정 연결.
 *
 * 회의를 열고 녹음하고 처리하는 것, 이야기를 나누는 것은 **한 줄도 안
 * 남깁니다** — 그건 고장이 아니라 이 기록의 범위입니다. 그 사실을 말해 주는
 * 것이 사람에게 쓸모 있습니다.
 *
 * ⚠️ **처음 쓴 문장은 저도 틀렸습니다.** 「사람의 **숫자**를 건드린 일만
 * 쌓입니다」라고 썼는데, 열넷 중 숫자를 건드리는 것은 둘뿐입니다
 * (`score_adjusted`·`weights_changed`). 업무를 완료로 옮긴 사람은 그 문장을
 * 읽고 또 한 번 거짓말을 들었을 것입니다. 범위를 말할 때는 **세어 보고**
 * 쓰십시오 — 이 결함을 고치면서 같은 실수를 반대 방향으로 했습니다.
 *
 * ⚠️ `github/feed.ts` 의 `describeEmptyFeed` 와 같은 규칙입니다 — **자기
 * 범위 안에서만** 말합니다.
 */

export interface EmptyReason {
  why: string;
  how: string;
}

/**
 * 팀 활동 기록이 빈 이유.
 *
 * ⚠️ **「아무도 안 바꿨다」고 말하지 않습니다.** 이 기록이 무엇을 받는지
 * 말하고, 무엇을 하면 남는지 말합니다.
 */
export function describeEmptyActivity(): EmptyReason {
  return {
    why: '이 기록에는 사람이 손으로 내린 결정만 쌓입니다 — 업무 후보 승인·업무 완료·역할 비중 같은 것입니다. 회의를 열거나 녹음하거나 이야기 나눈 것은 여기 안 남습니다.',
    how: '칸반에서 업무를 완료로 옮기거나 검토 화면에서 업무 후보를 승인하면 여기에 남습니다.',
  };
}

/**
 * 브라우저 창의 제목 — **화면마다 달라야 합니다** (WCAG 2.4.2, 수준 A).
 *
 * ## ⚠️ SPA 로 옮기면서 통째로 사라졌습니다
 *
 * 레거시는 화면마다 `.html` 이 하나씩이라 `<title>녹음 — TeamFlow</title>`
 * 처럼 파일에 적혀 있었습니다. SPA 는 `index.html` **한 장**이라 제목이
 * `TeamFlow` 하나로 고정됐고, 아홉 화면이 전부 같은 제목이었습니다.
 *
 * 이게 왜 문제인가 —
 *
 * - 낭독기는 화면이 바뀌면 **제목부터 읽습니다.** 전부 같으면 어디로
 *   왔는지 알 방법이 없습니다. SPA 는 페이지가 새로 뜨지 않아 제목 말고는
 *   "화면이 바뀌었다" 를 알릴 것이 없습니다
 * - 탭을 여럿 열어 두면 전부 `TeamFlow` 입니다
 * - 방문 기록·북마크도 전부 같은 이름으로 쌓입니다
 *
 * ## 형식은 한 곳에서
 *
 * `{화면} — TeamFlow`. 레거시 `.html` 열넷이 이미 이 형식으로 적혀
 * 있으므로 **같은 형식을 씁니다** — 두 벌이 되면 갈라집니다.
 * ⚠️ 구분자는 하이픈(`-`)이 아니라 **em 대시(`—`)** 입니다.
 */

/** 제품 이름. 제목의 꼬리에 붙습니다. */
export const APP_NAME = 'TeamFlow';

/**
 * 화면 이름 → 창 제목.
 *
 * ⚠️ 이름이 비었거나 없으면 **꼬리만** 돌려줍니다. `" — TeamFlow"` 처럼
 * 대시로 시작하는 제목이 뜨면 그 자체가 결함으로 보입니다.
 */
export function pageTitle(name: string | null | undefined): string {
  const trimmed = (name ?? '').trim();
  return trimmed === '' ? APP_NAME : `${trimmed} — ${APP_NAME}`;
}

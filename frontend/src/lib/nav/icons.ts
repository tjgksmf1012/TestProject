  // 체크 — "확인했어요". 획 하나뿐이라 12px 로 줄어도 안 뭉갭니다.
  check: '<path d="M4.5 12.5l5 5 10-11"/>',

  // 엄지 — "동의해요". 소맷단(왼쪽 네모)과 손을 나눠 그립니다.
  //
  // ⚠️ **상대 좌표(`l`·`h`·`v`)를 쓰지 마십시오.** `icons.test.ts` 는

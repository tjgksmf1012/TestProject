/**
 * 탭바 아이콘 — **직접 그린 path** 입니다.
 *
 * ## 왜 이모지를 버렸는가
 *
 * 예전에는 `🏠📋📊⚙️` 였습니다. 아이콘 파일이 0개라 그게 제일 싼
 * 방법이었는데, 값을 세 가지로 치릅니다.
 *
 *   1. **기기마다 다른 그림**입니다. macOS·Android·Windows 가 각각 자기
 *      이모지 서체로 그리므로, 같은 화면이 기기마다 다르게 보입니다.
 *      브랜드가 생길 자리가 없습니다
 *   2. **색이 박혀 있습니다.** 어두운 모드에서도 알록달록한 채로 남고,
 *      선택된 탭과 안 된 탭의 색 차이가 아이콘에는 안 걸립니다
 *   3. 크기·베이스라인이 서체에 딸려 있어 **세로 정렬이 틀어집니다**
 *
 * 지시서 §4.6 이 UI 이모지를 금지하는 이유가 그것입니다.
 *
 * ## ⚠️ 좌표는 **계산했습니다**
 *
 * 눈으로 그린 도형은 눈으로 고른 색과 같은 위험이 있습니다 — 스파이크
 * 팔레트에서 한 번 당했습니다(docs/16 Stage C). 그래서
 *
 *   · 24×24 격자, 안전 여백 3 (선 굵기 2 + round cap 이 1 씩 나감)
 *   · 좌표는 전부 정수 또는 .5 — 부분 픽셀이면 20px 에서 흐려집니다
 *   · 색은 `currentColor` — 탭의 글자색을 그대로 따라갑니다
 *
 * ## ⚠️ lucide 가 **아닙니다**
 *
 * 규격(24×24 · stroke 2 · round)만 같습니다. 네트워크가 없어 실제
 * lucide path 를 받을 수 없었고, 받은 척하면 다음 사람이 그걸 믿고
 * 원본과 대조하지 않습니다.
 */

/** 아이콘 이름. `links.ts` 의 `TAB_ICON` 이 이 중 하나를 고릅니다. */
export type IconName = 'home' | 'board' | 'track' | 'sliders' | 'meeting';

/**
 * 이름 → SVG 마크업.
 *
 * ⚠️ 이 값은 **화면에 그대로(raw) 들어갑니다.** 그래서 여기에는 상수
 * 문자열만 둡니다 — 변수를 끼워 넣는 순간 주입 통로가 됩니다.
 * `icons.test.ts` 가 그것을 고정합니다.
 */
const PATHS: Record<IconName, string> = {
  // 지붕(3,11)-(12,3)-(21,11) + 몸통 x 5.5~18.5, y 9.5~20
  home: '<path d="M3 11l9-8 9 8"/><path d="M5.5 9.5V20h13V9.5"/>',

  // 보드 3~21 × 4~20, 세로 칸막이 x=9·15 — 열 셋이 칸반의 전부다
  board: '<rect x="3" y="4" width="18" height="16" rx="2"/>' +
    '<path d="M9 4v16M15 4v16"/>',

  // ⭐ 이 제품의 시그니처가 아이콘이 된 것 — 시간축 위의 평행 트랙.
  // 가운데 줄은 **끊겨 있습니다.** 그 구멍이 이 화면의 값어치입니다.
  track: '<path d="M4 6h13"/><path d="M4 12h5M12 12h6"/><path d="M4 18h10"/>',

  // 말풍선 — 칸반 카드의 "회의에서 나온 업무" 표시.
  // ⚠️ 예전에는 `🗣` 였습니다. 그 자리는 **이 제품의 대표 주장이 카드에
  // 보이는 곳**이라, 기기마다 다른 그림이 나오면 안 됩니다.
  meeting: '<rect x="3" y="4" width="18" height="12" rx="2"/>' +
    '<path d="M8 16v4l4-4"/>',

  // 슬라이더 — 손잡이가 있어 트랙 아이콘과 헷갈리지 않는다
  sliders: '<path d="M4 8h16M4 16h16"/>' +
    '<circle cx="14" cy="8" r="2.5"/><circle cx="9" cy="16" r="2.5"/>',
};

/**
 * 탭 하나에 들어갈 `<svg>`.
 *
 * `aria-hidden` 입니다 — 바로 옆에 글자 라벨이 있으므로, 낭독기가
 * 그림까지 읽으면 같은 것을 두 번 말합니다.
 */
export function iconSvg(name: IconName): string {
  return (
    '<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">' +
    PATHS[name] +
    '</svg>'
  );
}

/** 정의된 이름 전부. 테스트가 훑습니다. */
export const ICON_NAMES: IconName[] = ['home', 'board', 'track', 'sliders', 'meeting'];

/**
 * 본문 표지(`main`)와 「본문으로 건너뛰기」.
 *
 * ## 이 제품에는 셸이 셋입니다
 *
 * 레거시 React 화면 열셋 · SPA 의 `AppShell` · SPA 밖 정적 화면 둘
 * (녹음 · 통화). 셋이 같은 이름을 각자 적으면 갈라집니다(대표 실패 ②).
 *
 * ## ⚠️ 「건너뛰기 링크」는 **모든 셸에 필요한 것이 아닙니다**
 *
 * WCAG 2.4.1 이 요구하는 것은 「화면마다 되풀이되는 덩어리를 **지나갈 수
 * 있을 것**」이고, 링크는 그 방법 **하나**일 뿐입니다. 되풀이되는 내비를
 * 본문 **뒤에** 두는 것도 같은 요구를 만족시킵니다.
 *
 * 재서 갈랐습니다(결함 421 회차 · Tab 순서):
 *
 *     SPA        Tab 1 = 건너뛰기 · 2~6 = 레일(되풀이) · 7 = 본문
 *                → 링크가 **필요합니다**. 있고, 잘 돕니다
 *     레거시      Tab 1 = 본문 · … · 67 = `#nav` · 72 = `#tabs`
 *                → 되풀이되는 것이 **뒤에** 있어 지나갈 것이 없습니다
 *
 * 그래서 레거시에 링크를 다는 것은 **모든 키보드 사용자에게 Tab 한 번을
 * 더 물리면서 아무 데도 데려가지 않는 것**입니다 — 안 답니다(재현 안 됨).
 *
 * ## ⚠️ 그런데 **본문 표지**는 셋 다 필요합니다
 *
 * 이건 Tab 순서와 상관없는 다른 축입니다. 낭독기 사용자는 표지 목록으로
 * 건너뜁니다. 레거시 화면 열셋에는 `main` 이 **하나도 없었고**, 재 보니
 * 레거시 홈은 컨트롤 스물 중 **열여섯이 어느 표지에도 안 들어** 있었습니다
 * (결함 421). SPA·정적 둘은 처음부터 `<main id="main-content">` 입니다.
 */

/** 본문 표지의 id. 세 셸이 같은 이름을 씁니다. */
export const MAIN_LANDMARK_ID = 'main-content';

/**
 * 건너뛰기 링크 글자.
 *
 * ⚠️ 되풀이되는 내비가 본문 **앞**에 오는 셸만 씁니다 — 위 표 참고.
 */
export const SKIP_TEXT = '본문으로 건너뛰기';

/** 그 링크의 `href`. 표적 이름을 손으로 적지 않게 합니다. */
export const SKIP_HREF = `#${MAIN_LANDMARK_ID}`;

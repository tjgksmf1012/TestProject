/**
 * **회의 시작 후 몇 분 몇 초인가** — 한 곳 (결함 353).
 *
 * ## ⛔ 회의 첫 발화의 시각이 빈칸으로 나갔습니다
 *
 * 8분짜리 회의를 실기 경로로 만들어 두 검토 화면을 열었더니, `0:00` 에
 * 시작한 첫 발화의 시각 칸이 **두 뿌리 다 비어 있었습니다.**
 *
 *     (빈칸)  김민수 · 정보 제공   0번째로 진행 상황을 공유합니다
 *      0:30   이하늘 · 정보 제공   1번째로 진행 상황을 공유합니다
 *
 * 빈칸은 「모른다」로 읽힙니다. 그런데 그 발화의 시각은 **정확히
 * 압니다** — 회의가 시작되자마자 한 말입니다.
 *
 * ## 왜 그랬나 — `0` 에 두 뜻이 실려 있었습니다
 *
 * 같은 자(`atText`)가 **두 곳에 똑같이 복사돼** 있었고(`findings.ts` ·
 * `minutes.ts`), 둘 다 `ms <= 0` 을 `null` 로 떨어뜨렸습니다. 그 규칙은
 * 원래 맞습니다 — 미해결 사안이나 사건은 **근거가 없으면 구간이 `0`** 이라
 * 「시각을 지어내지 않는다」가 옳습니다.
 *
 * 그런데 `evidenceView`(발화 한 줄)가 그 자를 가져다 썼습니다. **발화에는
 * 「모르는 시각」이 없습니다** — 언제나 제 시각이 있고, `0` 은 「회의
 * 시작과 동시에」라는 값입니다.
 *
 * ⚠️ **실기가 그 값을 만듭니다.** `to_segments` 가 `start_ms = start *
 * hop_ms` 로 만드는데 `start` 는 0부터입니다 — 녹음 버튼을 누르며 바로
 * 말을 시작하면 첫 구간이 정확히 `0` 입니다.
 *
 * ## 그래서 이름을 갈랐습니다
 *
 * 두 뜻에 각각 이름을 줍니다. 같은 이름이 두 뜻을 겸하면 다음 사람이
 * 또 아무거나 가져다 씁니다 — 이 저장소가 반복해서 당한 실패 ② 입니다.
 */

/** `750000` → `12:30`. 자리만 만듭니다 — 무엇이 `null` 인지는 아래가 정합니다. */
function mmss(ms: number): string {
  const total = Math.floor(ms / 1000);
  return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, '0')}`;
}

/**
 * **발화가 언제 나왔는가.** `0` 은 「회의 시작과 동시에」 — 시각입니다.
 *
 * ⚠️ 음수와 비정상 값만 `null` 입니다. 발화에는 「모르는 시각」이 없습니다.
 */
export function momentText(ms: number): string | null {
  if (!Number.isFinite(ms) || ms < 0) return null;
  return mmss(ms);
}

/**
 * **근거에서 잡은 구간의 시각.** `0` 은 「근거가 없다」는 뜻이라 `null`.
 *
 * 사건(`findings`)과 미해결 사안(`unresolved_issues`)이 씁니다 — 둘 다
 * 근거 발화가 없으면 서버가 구간을 `0~0` 으로 보냅니다. 그때 `0:00` 이라고
 * 적으면 **회의 맨 처음에 있었던 일**처럼 읽힙니다.
 *
 * ⚠️ 그래서 이쪽은 고치지 않았습니다 — 근거를 적어 내린 결정입니다.
 */
export function evidenceMomentText(ms: number): string | null {
  if (!Number.isFinite(ms) || ms <= 0) return null;
  return mmss(ms);
}

/**
 * **요청이 서버에 닿지도 못했을 때** 화면이 할 말.
 *
 * ## 무엇이 문제였나
 *
 * 화면이 실패를 다루는 방식은 두 갈래였습니다.
 *
 *     받아 오기(GET)  실패하면 `failureHtml` 로 이유와 다시 시도 버튼까지
 *     바꾸기(POST 등)  `!response.ok` 만 봤다 — **응답이 없는 경우는 없었다**
 *
 * `fetch` 는 서버가 400 을 주면 **성공**으로 끝나고(`ok === false`),
 * 서버에 닿지 못하면 **거부**합니다. 그래서 `!response.ok` 만 보는 코드는
 * 연결이 끊긴 경우를 통째로 놓칩니다. 그 뒤가 `void …` 나 `async` 클릭
 * 처리기면 거부가 아무 데도 안 걸리고 콘솔에만 남습니다.
 *
 * 브라우저에서 재현한 것 (기내·지하철·엘리베이터에서 늘 일어납니다):
 *
 *     새 프로젝트 만들기   아무 일도 안 일어남 · 오류 칸은 빈 채
 *     칸반 카드 옮기기     아무 일도 안 일어남 · 카드는 제자리
 *     기여도 확정          화면에 **"확정했습니다."** 가 그대로 남음  ← 최악
 *
 * 마지막 것은 `docs/05` §5 가 말하는 이 시스템의 **유일한 사람 개입
 * 지점**입니다. 확정이 안 됐는데 됐다고 읽히면, 팀은 합의한 값이 저장된
 * 줄 알고 화면을 닫습니다.
 *
 * ## 왜 문구를 여기 한 벌만 두는가
 *
 * 이미 예외를 잡던 세 곳은 이렇게 적혀 있었습니다.
 *
 *     `연결하지 못했습니다: ${String(err)}`   → 연결하지 못했습니다: TypeError: Failed to fetch
 *
 * 한글 화면에 브라우저의 영어 예외가 그대로 나옵니다 (결함 78·86 과 같은
 * 부류). 잡는 곳마다 문구를 새로 쓰면 이렇게 갈라지므로, 문구는 한 벌만
 * 둡니다.
 */

/**
 * 요청을 보낸다. **서버에 닿지 못하면 던지지 않고 `null` 을 돌려준다.**
 *
 * 함수를 받는 이유: `trySend(fetch(…))` 로 쓰면 `fetch` 가 그 자리에서
 * 던지는 경우(잘못된 URL 등)가 밖으로 새어 나갑니다. 안에서 부르면
 * 모든 실패가 여기서 끝납니다.
 *
 * ⚠️ 응답이 왔다는 것과 뜻대로 됐다는 것은 다릅니다. `null` 이 아니어도
 * `response.ok` 는 따로 봐야 합니다.
 */
export async function trySend(request: () => Promise<Response>): Promise<Response | null> {
  try {
    return await request();
  } catch {
    return null;
  }
}

/**
 * 서버에 닿지 못했을 때 화면에 그대로 넣을 한 줄.
 *
 * `what` 은 그 화면이 이미 쓰던 실패 문장입니다 (`'옮기지 못했습니다'`).
 * 무엇을 하려다 실패했는지는 화면마다 다르고, 왜 실패했는지는 같습니다.
 *
 * ⚠️ **"아무것도 바뀌지 않았습니다" 라고 쓰지 않습니다.** 요청이 나가기
 * 전에 끊겼는지, 서버까지 갔는데 답이 못 돌아왔는지 브라우저는 구분해
 * 주지 않습니다. 모르는 것을 안다고 쓰면 그게 더 나쁩니다.
 */
export function unreachableText(what: string): string {
  return `${what} — 서버에 닿지 못했습니다. 연결을 확인하고 다시 시도해 주세요.`;
}

/**
 * 예상하지 못한 오류일 때 화면이 할 말.
 *
 * ⚠️ 브라우저 예외를 문자열로 붙이지 않습니다. 화면 세 곳이 이랬습니다.
 *
 *     `전송 실패: ${String(err)}`   → 전송 실패: TypeError: Failed to fetch
 *
 * 사람은 저 영어에서 아무것도 못 얻고, 우리도 못 얻습니다 (스택이 없으니).
 * 원문은 **콘솔에** 남기고, 화면에는 사람이 할 수 있는 것을 적습니다.
 */
export function describeUnexpected(): string {
  return '알 수 없는 오류가 생겼습니다 — 새로고침해도 같으면 알려 주세요.';
}
